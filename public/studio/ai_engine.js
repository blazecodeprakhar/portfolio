/**
 * BlazeCode Studio AI Engine
 * Handles AI Code Generation requests via Built-in Synthesizer or API Integrations
 */

window.AIEngine = {
  config: {
    provider: localStorage.getItem('blaze_ai_provider') || 'builtIn',
    apiKey: localStorage.getItem('blaze_ai_key') || '',
    customUrl: localStorage.getItem('blaze_ai_url') || ''
  },

  saveConfig: function (provider, apiKey, customUrl) {
    this.config.provider = provider;
    this.config.apiKey = apiKey;
    this.config.customUrl = customUrl;

    localStorage.setItem('blaze_ai_provider', provider);
    localStorage.setItem('blaze_ai_key', apiKey);
    localStorage.setItem('blaze_ai_url', customUrl);
  },

  generateCode: async function (promptText, language) {
    const provider = this.config.provider;

    if (provider === 'gemini' && this.config.apiKey) {
      return await this.generateGemini(promptText, language);
    } else if (provider === 'openai' && this.config.apiKey) {
      return await this.generateOpenAI(promptText, language);
    } else if (provider === 'custom' && this.config.customUrl) {
      return await this.generateCustom(promptText, language);
    } else {
      // Default: Built-in Smart Synthesizer
      return this.synthesizeBuiltIn(promptText, language);
    }
  },

  synthesizeBuiltIn: function (promptText, lang) {
    const p = promptText.toLowerCase();

    // Template Generator Logic
    if (p.includes('pattern') || p.includes('star') || p.includes('pyramid')) {
      return this.getPatternCode(lang);
    } else if (p.includes('fibonacci') || p.includes('fibo')) {
      return this.getFibonacciCode(lang);
    } else if (p.includes('prime') || p.includes('prime number')) {
      return this.getPrimeCode(lang);
    } else if (p.includes('sort') || p.includes('bubble')) {
      return this.getSortCode(lang);
    } else if (p.includes('hello') || p.includes('start')) {
      return this.getHelloCode(lang);
    } else if (lang === 'html' || p.includes('web') || p.includes('page') || p.includes('card')) {
      return `<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="UTF-8">
  <title>BlazeCode AI Generated Component</title>
  <style>
    body { font-family: sans-serif; background: #0f172a; color: #fff; display: flex; justify-content: center; align-items: center; height: 100vh; margin: 0; }
    .card { background: rgba(255,255,255,0.05); padding: 2rem; border-radius: 16px; border: 1px solid rgba(255,255,255,0.1); backdrop-filter: blur(10px); text-align: center; max-width: 400px; }
    h1 { color: #BD4FF4; margin-bottom: 0.5rem; }
    button { background: linear-gradient(135deg, #BD4FF4, #E48A60); border: none; color: white; padding: 10px 20px; border-radius: 8px; font-weight: bold; cursor: pointer; margin-top: 1rem; }
  </style>
</head>
<body>
  <div class="card">
    <h1>✨ BlazeCode Card</h1>
    <p>Generated by BlazeCode AI Synthesizer for prompt: "${promptText}"</p>
    <button onclick="alert('Hello from BlazeCode Studio!')">Interact</button>
  </div>
</body>
</html>`;
    }

    // Default Code Generation Template
    return this.getDefaultGeneratedCode(promptText, lang);
  },

  getPatternCode: function(lang) {
    switch(lang) {
      case 'python':
        return `# Pattern Printing in Python
n = 5
for i in range(1, n + 1):
    print(" " * (n - i) + "* " * i)
for i in range(n - 1, 0, -1):
    print(" " * (n - i) + "* " * i)`;
      case 'javascript':
        return `// Diamond Pattern in JavaScript
const n = 5;
for (let i = 1; i <= n; i++) {
  console.log(" ".repeat(n - i) + "* ".repeat(i));
}
for (let i = n - 1; i >= 1; i--) {
  console.log(" ".repeat(n - i) + "* ".repeat(i));
}`;
      case 'cpp':
        return `#include <iostream>
using namespace std;

int main() {
    int n = 5;
    for(int i = 1; i <= n; i++) {
        for(int j = i; j < n; j++) cout << " ";
        for(int j = 1; j <= (2*i-1); j++) cout << "*";
        cout << endl;
    }
    return 0;
}`;
      case 'c':
        return `#include <stdio.h>

int main() {
    int n = 5;
    for(int i = 1; i <= n; i++) {
        for(int j = i; j < n; j++) printf(" ");
        for(int j = 1; j <= (2*i-1); j++) printf("*");
        printf("\\n");
    }
    return 0;
}`;
      case 'java':
        return `public class Main {
    public static void main(String[] args) {
        int n = 5;
        for (int i = 1; i <= n; i++) {
            for (int j = i; j < n; j++) System.out.print(" ");
            for (int j = 1; j <= (2 * i - 1); j++) System.out.print("*");
            System.out.println();
        }
    }
}`;
      default:
        return `// Pattern Generator for ${lang}\nfor i := 1; i <= 5; i++ { print("*") }`;
    }
  },

  getFibonacciCode: function(lang) {
    switch(lang) {
      case 'python':
        return `# Fibonacci Sequence Generator
def fibonacci(n):
    sequence = [0, 1]
    while len(sequence) < n:
        sequence.append(sequence[-1] + sequence[-2])
    return sequence

print("First 10 Fibonacci numbers:", fibonacci(10))`;
      case 'javascript':
        return `// Fibonacci Sequence Generator in JS
function fibonacci(n) {
  let seq = [0, 1];
  for (let i = 2; i < n; i++) {
    seq.push(seq[i - 1] + seq[i - 2]);
  }
  return seq;
}
console.log("Fibonacci Series:", fibonacci(10));`;
      case 'cpp':
        return `#include <iostream>
using namespace std;

void fibonacci(int n) {
    long long a = 0, b = 1, next;
    for (int i = 1; i <= n; ++i) {
        cout << a << " ";
        next = a + b;
        a = b;
        b = next;
    }
    cout << endl;
}

int main() {
    cout << "Fibonacci Series (10 terms): ";
    fibonacci(10);
    return 0;
}`;
      case 'java':
        return `public class Main {
    public static void main(String[] args) {
        int n = 10, t1 = 0, t2 = 1;
        System.out.print("Fibonacci Series: ");
        for (int i = 1; i <= n; ++i) {
            System.out.print(t1 + " ");
            int sum = t1 + t2;
            t1 = t2;
            t2 = sum;
        }
    }
}`;
      default:
        return `// Fibonacci in ${lang}\nfmt.Println("Fibonacci generator ready")`;
    }
  },

  getPrimeCode: function(lang) {
    return `# Prime Number Checker in ${lang}
def is_prime(n):
    if n <= 1:
        return False
    for i in range(2, int(n**0.5) + 1):
        if n % i == 0:
            return False
    return True

primes = [x for x in range(1, 50) if is_prime(x)]
print("Prime numbers up to 50:", primes)`;
  },

  getSortCode: function(lang) {
    return `// Bubble Sort Implementation in ${lang}
function bubbleSort(arr) {
  let len = arr.length;
  for (let i = 0; i < len; i++) {
    for (let j = 0; j < len - i - 1; j++) {
      if (arr[j] > arr[j + 1]) {
        let temp = arr[j];
        arr[j] = arr[j + 1];
        arr[j + 1] = temp;
      }
    }
  }
  return arr;
}

console.log("Sorted Array:", bubbleSort([64, 34, 25, 12, 22, 11, 90]));`;
  },

  getHelloCode: function(lang) {
    switch(lang) {
      case 'python': return `print("Hello, World from BlazeCode Studio!")\nprint("Python 3 Execution Ready!")`;
      case 'javascript': return `console.log("Hello, World from BlazeCode Studio!");\nconsole.log("JS Runtime Active!");`;
      case 'cpp': return `#include <iostream>\nusing namespace std;\n\nint main() {\n    cout << "Hello, World from BlazeCode Studio!" << endl;\n    return 0;\n}`;
      case 'c': return `#include <stdio.h>\n\nint main() {\n    printf("Hello, World from BlazeCode Studio!\\n");\n    return 0;\n}`;
      case 'java': return `public class Main {\n    public static void main(String[] args) {\n        System.out.println("Hello, World from BlazeCode Studio!");\n    }\n}`;
      case 'go': return `package main\nimport "fmt"\n\nfunc main() {\n    fmt.Println("Hello, World from BlazeCode Studio!")\n}`;
      case 'rust': return `fn main() {\n    println!("Hello, World from BlazeCode Studio!");\n}`;
      default: return `console.log("Hello World!");`;
    }
  },

  getDefaultGeneratedCode: function(promptText, lang) {
    return `// Code generated for prompt: "${promptText}"
// Language: ${lang.toUpperCase()}

function executeTask() {
    console.log("Task initialized for prompt:", "${promptText}");
    const data = [10, 20, 30, 40, 50];
    const result = data.map(x => x * 2);
    console.log("Processed Results:", result);
}

executeTask();`;
  },

  generateGemini: async function(promptText, lang) {
    try {
      const response = await fetch(`https://generativelanguage.googleapis.com/v1beta/models/gemini-pro:generateContent?key=${this.config.apiKey}`, {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({
          contents: [{
            parts: [{
              text: `Write clean, functional ${lang} code for the following request. Return ONLY code without markdown codeblocks or explanation: ${promptText}`
            }]
          }]
        })
      });
      const data = await response.json();
      let text = data.candidates?.[0]?.content?.parts?.[0]?.text || '';
      return text.replace(/```[a-z]*\n?/gi, '').replace(/```/g, '').trim();
    } catch(err) {
      console.warn("Gemini API call failed, falling back to built-in synthesizer:", err);
      return this.synthesizeBuiltIn(promptText, lang);
    }
  },

  generateOpenAI: async function(promptText, lang) {
    try {
      const response = await fetch('https://api.openai.com/v1/chat/completions', {
        method: 'POST',
        headers: {
          'Content-Type': 'application/json',
          'Authorization': `Bearer ${this.config.apiKey}`
        },
        body: JSON.stringify({
          model: 'gpt-3.5-turbo',
          messages: [{
            role: 'user',
            content: `Write executable ${lang} code only for: ${promptText}`
          }]
        })
      });
      const data = await response.json();
      let text = data.choices?.[0]?.message?.content || '';
      return text.replace(/```[a-z]*\n?/gi, '').replace(/```/g, '').trim();
    } catch(err) {
      console.warn("OpenAI API call failed, falling back to built-in synthesizer:", err);
      return this.synthesizeBuiltIn(promptText, lang);
    }
  },

  generateCustom: async function(promptText, lang) {
    try {
      const response = await fetch(this.config.customUrl, {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({ prompt: promptText, language: lang })
      });
      const data = await response.json();
      return data.code || data.result || this.synthesizeBuiltIn(promptText, lang);
    } catch(err) {
      return this.synthesizeBuiltIn(promptText, lang);
    }
  }
};
